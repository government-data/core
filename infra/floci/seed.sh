#!/usr/bin/env bash
# Creates in Floci what the licensing cloud expects from infra/aws (the
# releases bucket, the ECR repositories and what the test instances need) and
# leaves in infra/floci/licencias.env the variables to run `licencias` against
# it. It can run as many times as needed.
set -euo pipefail

export AWS_ENDPOINT_URL="${AWS_ENDPOINT_URL:-http://localhost:4566}"
export AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test AWS_DEFAULT_REGION=us-east-1
unset AWS_PROFILE AWS_SESSION_TOKEN

project=orquestador
domain=orquestador.test
here="$(cd "$(dirname "$0")" && pwd)"

account="$(aws sts get-caller-identity --query Account --output text)"
if [ "$account" != "000000000000" ]; then
  echo "The account is $account, not Floci's: nothing is seeded." >&2
  exit 1
fi

bucket="$project-releases-$account"
aws s3api head-bucket --bucket "$bucket" 2>/dev/null ||
  aws s3api create-bucket --bucket "$bucket" >/dev/null
echo "s3://$bucket"

for repo in api web licencias cuenta; do
  aws ecr describe-repositories --repository-names "$project/$repo" >/dev/null 2>&1 ||
    aws ecr create-repository --repository-name "$project/$repo" >/dev/null
  echo "ecr $project/$repo"
done

zone="$(aws route53 list-hosted-zones-by-name --dns-name "$domain" \
  --query "HostedZones[?Name=='$domain.'].Id | [0]" --output text)"
if [ "$zone" = "None" ] || [ -z "$zone" ]; then
  zone="$(aws route53 create-hosted-zone --name "$domain" \
    --caller-reference "seed-$(date +%s)" --query HostedZone.Id --output text)"
fi
zone="${zone#/hostedzone/}"
echo "route53 $domain ($zone)"

# The AWS names are the ones infra/aws gives them (the licensing cloud reads them).
name="$project-instancia-prueba"
group="$(aws ec2 describe-security-groups --filters "Name=group-name,Values=$name" \
  --query 'SecurityGroups[0].GroupId' --output text)"
if [ "$group" = "None" ] || [ -z "$group" ]; then
  group="$(aws ec2 create-security-group --group-name "$name" \
    --description "Test instances (Floci)" --query GroupId --output text)"
fi
echo "ec2 group $group"

aws iam get-role --role-name "$name" >/dev/null 2>&1 ||
  aws iam create-role --role-name "$name" --assume-role-policy-document \
    '{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Principal":{"Service":"ec2.amazonaws.com"},"Action":"sts:AssumeRole"}]}' >/dev/null
if ! aws iam get-instance-profile --instance-profile-name "$name" >/dev/null 2>&1; then
  aws iam create-instance-profile --instance-profile-name "$name" >/dev/null
  aws iam add-role-to-instance-profile --instance-profile-name "$name" --role-name "$name"
fi
echo "iam profile $name"

ami="$(aws ec2 describe-images --query 'Images[0].ImageId' --output text)"
echo "ec2 ami $ami"

# The same infra/aws/pruebas.tf stores, for whatever reads it from SSM.
for pair in "zona=$zone" "grupo=$group" "perfil=$name" "ami=$ami" "bucket=$bucket"; do
  aws ssm put-parameter --name "/$project/nube/pruebas-${pair%%=*}" --type String \
    --value "${pair#*=}" --overwrite >/dev/null
done
echo "ssm /$project/nube/pruebas-*"

cat >"$here/licencias.env" <<EOF
# Generated by infra/floci/seed.sh: the licensing cloud against Floci.
LICENCIAS_AWS_ENDPOINT_URL=$AWS_ENDPOINT_URL
LICENCIAS_AWS_ACCESS_KEY_ID=test
LICENCIAS_AWS_SECRET_ACCESS_KEY=test
LICENCIAS_AWS_REGION=us-east-1
LICENCIAS_PRUEBAS_ZONA=$zone
LICENCIAS_PRUEBAS_GRUPO=$group
LICENCIAS_PRUEBAS_PERFIL=$name
LICENCIAS_PRUEBAS_AMI=$ami
LICENCIAS_PRUEBAS_BUCKET=$bucket
LICENCIAS_DOMINIO_EMPRESAS=$domain
EOF
echo "variables in infra/floci/licencias.env"
