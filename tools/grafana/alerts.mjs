// Writes Grafana's alerting provisioning of decision 0072 (points 5 to 8):
//   node tools/grafana/alerts.mjs            (part of pnpm run gen:grafana)
// Reads infra/observability/grafana/definition/alerts.json (the format is
// described in alerting.mjs) and crates/texts/locales/{es,en}.json (the keys
// machines.alerts.*), and rewrites infra/observability/grafana/provisioning/
// alerting/{rules,templates,policies,contact-points}.yml. It fails when a
// key is missing in either language. The output is deterministic, so
// `pnpm run check:grafana` can compare it with git. Directory 755 and files
// 644: Grafana (uid 472) reads them.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  LANGUAGES,
  checkNoEnv,
  checkTexts,
  contactPoints,
  flatten,
  policies,
  rules,
  templates,
} from "./alerting.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const grafana = path.join(root, "infra/observability/grafana");
const target = path.join(grafana, "provisioning/alerting");

const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));

/** A scalar as YAML: strings double-quoted as JSON, which YAML reads as is. */
function scalar(value) {
  if (typeof value === "string" || typeof value === "number" || typeof value === "boolean")
    return JSON.stringify(value);
  throw new Error(`no YAML for ${typeof value}`);
}

function key(name) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`a bad YAML key: ${name}`);
  return name;
}

/** YAML of plain data in block style; a multi-line string as a literal block. */
function yaml(value, indent = "") {
  const lines = [];
  const item = (prefix, v, inner) => {
    if (typeof v === "string" && v.includes("\n")) {
      if (/[ \t]\n|\t/.test(v)) throw new Error("a multi-line string with a tab or trailing space");
      lines.push(
        `${prefix} |`,
        ...v
          .replace(/\n$/, "")
          .split("\n")
          .map((l) => (l ? inner + l : "")),
      );
    } else if (v !== null && typeof v === "object" && Object.keys(v).length) {
      if (Array.isArray(v) && v.every((x) => typeof x !== "object")) {
        lines.push(`${prefix} [${v.map(scalar).join(", ")}]`);
      } else {
        lines.push(prefix, yaml(v, inner));
      }
    } else if (v !== null && typeof v === "object") {
      lines.push(`${prefix} ${Array.isArray(v) ? "[]" : "{}"}`);
    } else {
      lines.push(`${prefix} ${scalar(v)}`);
    }
  };
  if (Array.isArray(value)) {
    for (const v of value) {
      if (v !== null && typeof v === "object" && !Array.isArray(v)) {
        const body = yaml(v, `${indent}  `).split("\n");
        lines.push(`${indent}- ${body[0].trimStart()}`, ...body.slice(1));
      } else {
        item(`${indent}-`, v, `${indent}  `);
      }
    }
  } else {
    for (const [k, v] of Object.entries(value)) item(`${indent}${key(k)}:`, v, `${indent}  `);
  }
  return lines.join("\n");
}

const HEADER = `# Generated by tools/grafana/alerts.mjs from
# infra/observability/grafana/definition/alerts.json and crates/texts
# (decision 0072): change those and run \`pnpm run gen:grafana\`, never this file.
`;

function main() {
  const def = readJson(path.join(grafana, "definition/alerts.json"));
  const texts = Object.fromEntries(
    LANGUAGES.map((lang) => [
      lang,
      flatten(readJson(path.join(root, `crates/texts/locales/${lang}.json`))),
    ]),
  );
  checkTexts(def, texts);
  const output = {
    "rules.yml": rules(def, texts),
    "templates.yml": templates(texts),
    "policies.yml": policies(def),
    "contact-points.yml": contactPoints(def),
  };
  for (const [file, content] of Object.entries(output)) {
    if (file !== "contact-points.yml") checkNoEnv(content, file);
  }
  fs.mkdirSync(target, { recursive: true });
  fs.chmodSync(target, 0o755);
  for (const entry of fs.readdirSync(target)) {
    if (!(entry in output)) fs.rmSync(path.join(target, entry));
  }
  for (const [file, content] of Object.entries(output)) {
    fs.writeFileSync(path.join(target, file), `${HEADER}${yaml(content)}\n`);
    fs.chmodSync(path.join(target, file), 0o644);
    console.log(`wrote ${path.relative(root, path.join(target, file))}`);
  }
}

try {
  main();
} catch (e) {
  console.error(`grafana alerts: ${e.message}`);
  process.exit(1);
}
